-- PROVISIONAL. Propuesta para el paso 1 del PR #41 (GEN-03-BE).
-- El Scrum Master decidió el 23/11/2026 que el dueño del modelo Evaluacion y sus tablas es el #41,
-- con ids Long (BIGINT con identidad). Mientras ese paso no esté en main, E3 necesita estas tablas
-- para guardar la evaluación. Cuando el #41 entregue su modelo, esta migración se retira de la rama
-- de GEN-02-BE (aún no fusionada) y E3 pasa a usar las tablas del #41.
-- Fuente: Documento general §4.2, ENT-COM-05 (Evaluacion) y ENT-COM-06 (EvaluacionSubprueba);
-- Documento BFA §4.3, ENT-BFA-11 (AplicacionFluidezBFA) y RF-FV-06.
-- Depende del catálogo de GEN-07-BE (test, version_formulario, configuracion_subprueba) y de la
-- migración anterior (sujeto, periodo).

CREATE TABLE evaluacion (
    id_evaluacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_sujeto BIGINT NOT NULL,
    id_version_formulario BIGINT NOT NULL,
    -- Derivado de la versión (ENT-COM-05): se guarda para exigir una sola evaluación
    -- abierta por sujeto, test y período. La aplicación comprueba que coincida.
    id_test BIGINT NOT NULL,
    id_periodo BIGINT NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'EN_CURSO',
    iniciada_en TIMESTAMPTZ NOT NULL,
    finalizada_en TIMESTAMPTZ,

    CONSTRAINT fk_evaluacion_sujeto FOREIGN KEY (id_sujeto) REFERENCES sujeto (id_sujeto),
    CONSTRAINT fk_evaluacion_version
        FOREIGN KEY (id_version_formulario)
        REFERENCES version_formulario (id_version_formulario),
    CONSTRAINT fk_evaluacion_test FOREIGN KEY (id_test) REFERENCES test (id_test),
    CONSTRAINT fk_evaluacion_periodo FOREIGN KEY (id_periodo) REFERENCES periodo (id_periodo),
    CONSTRAINT chk_evaluacion_estado CHECK (estado IN ('EN_CURSO', 'FINALIZADA')),
    CONSTRAINT chk_evaluacion_finalizada
        CHECK ((estado = 'FINALIZADA') = (finalizada_en IS NOT NULL)),
    CONSTRAINT chk_evaluacion_fechas
        CHECK (finalizada_en IS NULL OR finalizada_en >= iniciada_en)
);

-- E3 / DOC-04 CU-GEN-04: un sujeto no puede tener dos evaluaciones abiertas del mismo
-- test en el mismo período. Protege también frente a dos solicitudes simultáneas.
CREATE UNIQUE INDEX uq_evaluacion_en_curso
    ON evaluacion (id_sujeto, id_test, id_periodo)
    WHERE estado = 'EN_CURSO';

CREATE INDEX ix_evaluacion_sujeto ON evaluacion (id_sujeto);
CREATE INDEX ix_evaluacion_periodo ON evaluacion (id_periodo);

CREATE TABLE evaluacion_subprueba (
    id_evaluacion_subprueba BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_evaluacion BIGINT NOT NULL,
    id_configuracion_subprueba BIGINT NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    iniciada_en TIMESTAMPTZ,
    fin_limite TIMESTAMPTZ,
    cerrada_en TIMESTAMPTZ,

    CONSTRAINT fk_evaluacion_subprueba_evaluacion
        FOREIGN KEY (id_evaluacion) REFERENCES evaluacion (id_evaluacion),
    CONSTRAINT fk_evaluacion_subprueba_configuracion
        FOREIGN KEY (id_configuracion_subprueba)
        REFERENCES configuracion_subprueba (id_configuracion_subprueba),
    CONSTRAINT uq_evaluacion_subprueba_configuracion
        UNIQUE (id_evaluacion, id_configuracion_subprueba),
    CONSTRAINT chk_evaluacion_subprueba_estado
        CHECK (estado IN ('PENDIENTE', 'ACTIVA', 'CERRADA')),
    CONSTRAINT chk_evaluacion_subprueba_pendiente
        CHECK (
            estado <> 'PENDIENTE'
            OR (iniciada_en IS NULL AND fin_limite IS NULL AND cerrada_en IS NULL)
        ),
    CONSTRAINT chk_evaluacion_subprueba_iniciada
        CHECK (estado = 'PENDIENTE' OR iniciada_en IS NOT NULL),
    CONSTRAINT chk_evaluacion_subprueba_cerrada
        CHECK ((estado = 'CERRADA') = (cerrada_en IS NOT NULL)),
    CONSTRAINT chk_evaluacion_subprueba_fin_limite
        CHECK (fin_limite IS NULL OR fin_limite > iniciada_en),
    CONSTRAINT chk_evaluacion_subprueba_cierre
        CHECK (cerrada_en IS NULL OR cerrada_en >= iniciada_en)
);

CREATE INDEX ix_evaluacion_subprueba_evaluacion ON evaluacion_subprueba (id_evaluacion);

-- Letra inicial de Fluidez Verbal asignada en E3 (extensión 0..1 de la ejecución FV).
CREATE TABLE aplicacion_fluidez_bfa (
    id_evaluacion_subprueba BIGINT PRIMARY KEY,
    letra_inicial VARCHAR(1) NOT NULL,

    CONSTRAINT fk_aplicacion_fluidez_bfa_ejecucion
        FOREIGN KEY (id_evaluacion_subprueba)
        REFERENCES evaluacion_subprueba (id_evaluacion_subprueba),
    CONSTRAINT chk_aplicacion_fluidez_bfa_letra
        CHECK (letra_inicial ~ '^[A-ZÑ]$')
);
