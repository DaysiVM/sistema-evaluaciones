-- GEN-06-BE: cuentas de acceso y sesiones
-- ENT-COM-14 Cuenta (Documento general §4): credencial de acceso; no reemplaza al Sujeto.
-- La contrasena solo se guarda como resumen cifrado y el token de sesion solo como su resumen.
-- Sin datos: las pruebas crean sus cuentas ficticias.

-- =====================================================
-- 1. CUENTA
-- =====================================================

CREATE TABLE cuenta (
                      id_cuenta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      correo VARCHAR(254) NOT NULL,
                      resumen_contrasena VARCHAR(200) NOT NULL,
                      nombres VARCHAR(120) NOT NULL,
                      apellidos VARCHAR(120) NOT NULL,
                      estado VARCHAR(20) NOT NULL,

                      CONSTRAINT chk_cuenta_correo
                        CHECK (BTRIM(correo) <> ''),

                      CONSTRAINT chk_cuenta_nombres
                        CHECK (BTRIM(nombres) <> ''),

                      CONSTRAINT chk_cuenta_apellidos
                        CHECK (BTRIM(apellidos) <> ''),

                      CONSTRAINT chk_cuenta_estado
                        CHECK (estado IN ('ACTIVA', 'INHABILITADA'))
);

-- El correo es unico sin distinguir mayusculas (E13: CUENTA_EXISTENTE)
CREATE UNIQUE INDEX uq_cuenta_correo ON cuenta (LOWER(correo));

-- =====================================================
-- 2. ROLES DE LA CUENTA
-- =====================================================

CREATE TABLE cuenta_rol (
                          id_cuenta BIGINT NOT NULL,
                          rol VARCHAR(20) NOT NULL,

                          CONSTRAINT pk_cuenta_rol
                            PRIMARY KEY (id_cuenta, rol),

                          CONSTRAINT fk_cuenta_rol_cuenta
                            FOREIGN KEY (id_cuenta) REFERENCES cuenta(id_cuenta),

                          CONSTRAINT chk_cuenta_rol_rol
                            CHECK (rol IN ('SUJETO', 'ACADEMICO', 'COORDINADOR', 'PSICOLOGO', 'DECANO'))
);

-- =====================================================
-- 3. SESION
-- =====================================================

CREATE TABLE sesion (
                      id_sesion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      id_cuenta BIGINT NOT NULL,
                      resumen_token CHAR(64) NOT NULL UNIQUE,
                      rol_activo VARCHAR(20) NOT NULL,
                      abierta_en TIMESTAMPTZ NOT NULL,
                      expira_en TIMESTAMPTZ,
                      cerrada_en TIMESTAMPTZ,

                      CONSTRAINT fk_sesion_cuenta
                        FOREIGN KEY (id_cuenta) REFERENCES cuenta(id_cuenta),

                      CONSTRAINT fk_sesion_rol_activo
                        FOREIGN KEY (id_cuenta, rol_activo) REFERENCES cuenta_rol(id_cuenta, rol),

                      CONSTRAINT chk_sesion_expira
                        CHECK (expira_en IS NULL OR expira_en > abierta_en),

                      CONSTRAINT chk_sesion_cerrada
                        CHECK (cerrada_en IS NULL OR cerrada_en >= abierta_en)
);

CREATE INDEX ix_sesion_cuenta ON sesion (id_cuenta);
