CREATE TABLE evento_auditoria (
    id_evento_auditoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cuenta BIGINT NOT NULL REFERENCES cuenta(id_cuenta),
    accion TEXT NOT NULL CHECK (BTRIM(accion) <> ''),
    entidad_tipo TEXT NOT NULL CHECK (BTRIM(entidad_tipo) <> ''),
    entidad_id BIGINT NOT NULL,
    ocurrido_en TIMESTAMPTZ NOT NULL DEFAULT statement_timestamp(),
    id_evaluacion BIGINT REFERENCES evaluacion(id_evaluacion),
    id_evaluacion_subprueba BIGINT REFERENCES evaluacion_subprueba(id_evaluacion_subprueba),
    detalle TEXT
);
