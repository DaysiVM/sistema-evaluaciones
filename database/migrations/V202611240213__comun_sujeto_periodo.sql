CREATE TABLE sujeto (
    id_sujeto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_institucional VARCHAR(80),
    nombres VARCHAR(200) NOT NULL,
    apellidos VARCHAR(200) NOT NULL,
    fecha_nacimiento DATE,
    sexo_referencia VARCHAR(40),

    CONSTRAINT uq_sujeto_codigo_institucional UNIQUE (codigo_institucional),
    CONSTRAINT chk_sujeto_codigo_institucional
        CHECK (codigo_institucional IS NULL OR BTRIM(codigo_institucional) <> ''),
    CONSTRAINT chk_sujeto_nombres CHECK (BTRIM(nombres) <> ''),
    CONSTRAINT chk_sujeto_apellidos CHECK (BTRIM(apellidos) <> ''),
    CONSTRAINT chk_sujeto_sexo_referencia
        CHECK (sexo_referencia IS NULL OR BTRIM(sexo_referencia) <> '')
);

CREATE TABLE periodo (
    id_periodo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(40) NOT NULL,
    nombre VARCHAR(200) NOT NULL,
    fecha_inicio DATE,
    fecha_fin DATE,
    activo BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT uq_periodo_codigo UNIQUE (codigo),
    CONSTRAINT chk_periodo_codigo CHECK (BTRIM(codigo) <> ''),
    CONSTRAINT chk_periodo_nombre CHECK (BTRIM(nombre) <> ''),
    CONSTRAINT chk_periodo_fechas
        CHECK (fecha_inicio IS NULL OR fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);
