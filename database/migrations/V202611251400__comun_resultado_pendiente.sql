-- GEN-39/38: contenedor comun; no publica ni inventa puntajes faltantes.
CREATE TABLE resultado (
 id_resultado BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_evaluacion BIGINT NOT NULL UNIQUE REFERENCES evaluacion(id_evaluacion),
 estado TEXT NOT NULL CHECK(estado IN ('CALCULANDO','PENDIENTE_VALIDACION','DISPONIBLE')),
 referencia_revision_vigente BIGINT,
 creado_en TIMESTAMPTZ NOT NULL DEFAULT statement_timestamp(),
 CONSTRAINT ck_resultado_publicado CHECK(estado <> 'DISPONIBLE' OR referencia_revision_vigente IS NOT NULL)
);
