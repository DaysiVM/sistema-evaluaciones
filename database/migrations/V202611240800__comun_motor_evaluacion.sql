-- GEN-37-BE: motor de evaluacion 1/2 (tablas). Origen: PR #41, ids numericos segun el contrato.
-- id_sujeto e id_periodo no llevan FK todavia: sus tablas llegan con GEN-35-BE, que agrega la FK.

CREATE TABLE evaluacion (
    id_evaluacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_sujeto BIGINT NOT NULL,
    id_periodo BIGINT NOT NULL,
    id_test BIGINT NOT NULL,
    id_version_formulario BIGINT NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'EN_CURSO',
    fecha_inicio TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_fin TIMESTAMPTZ,

    CONSTRAINT fk_evaluacion_test
        FOREIGN KEY (id_test) REFERENCES test(id_test),
    CONSTRAINT fk_evaluacion_version_formulario
        FOREIGN KEY (id_version_formulario) REFERENCES version_formulario(id_version_formulario),
    CONSTRAINT ck_evaluacion_estado CHECK (estado IN ('EN_CURSO', 'FINALIZADA')),
    CONSTRAINT ck_evaluacion_fin CHECK (
        (estado = 'EN_CURSO' AND fecha_fin IS NULL)
        OR (estado = 'FINALIZADA' AND fecha_fin IS NOT NULL))
);

CREATE INDEX idx_evaluacion_sujeto ON evaluacion(id_sujeto);

CREATE TABLE evaluacion_subprueba (
    id_evaluacion_subprueba BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_evaluacion BIGINT NOT NULL,
    id_configuracion_subprueba BIGINT NOT NULL,
    codigo VARCHAR(80) NOT NULL,
    nombre VARCHAR(200) NOT NULL,
    orden INTEGER NOT NULL,
    duracion_segundos INTEGER NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    instrucciones TEXT,
    permitir_retroceso BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_inicio TIMESTAMPTZ,
    fecha_fin_limite TIMESTAMPTZ,
    fecha_cierre TIMESTAMPTZ,
    letra_inicial VARCHAR(1),
    maximo_entradas INTEGER NOT NULL DEFAULT 75,

    CONSTRAINT fk_eval_subprueba_evaluacion
        FOREIGN KEY (id_evaluacion) REFERENCES evaluacion(id_evaluacion) ON DELETE CASCADE,
    CONSTRAINT fk_eval_subprueba_configuracion
        FOREIGN KEY (id_configuracion_subprueba)
        REFERENCES configuracion_subprueba(id_configuracion_subprueba),
    CONSTRAINT uk_eval_subprueba UNIQUE (id_evaluacion, codigo),
    CONSTRAINT ck_eval_subprueba_maximo CHECK (maximo_entradas BETWEEN 1 AND 75),
    CONSTRAINT ck_eval_subprueba_estado CHECK (estado IN ('PENDIENTE', 'ACTIVA', 'CERRADA')),
    CONSTRAINT ck_eval_subprueba_tiempo CHECK (
        (estado = 'PENDIENTE' AND fecha_inicio IS NULL
            AND fecha_fin_limite IS NULL AND fecha_cierre IS NULL)
        OR (estado = 'ACTIVA' AND fecha_inicio IS NOT NULL
            AND fecha_fin_limite > fecha_inicio AND fecha_cierre IS NULL)
        OR (estado = 'CERRADA' AND fecha_inicio IS NOT NULL
            AND fecha_fin_limite > fecha_inicio AND fecha_cierre IS NOT NULL))
);

-- Una sola subprueba activa por evaluacion.
CREATE UNIQUE INDEX uq_eval_subprueba_activa
    ON evaluacion_subprueba(id_evaluacion) WHERE estado = 'ACTIVA';

CREATE TABLE respuesta_evaluacion (
    id_respuesta_evaluacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_evaluacion BIGINT NOT NULL,
    subprueba_codigo VARCHAR(80) NOT NULL,
    id_pregunta BIGINT,
    id_opcion BIGINT,
    valor_texto TEXT,
    orden_entrada INTEGER NOT NULL DEFAULT 1,
    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_respuesta_subprueba
        FOREIGN KEY (id_evaluacion, subprueba_codigo)
        REFERENCES evaluacion_subprueba(id_evaluacion, codigo) ON DELETE CASCADE,
    CONSTRAINT fk_respuesta_pregunta
        FOREIGN KEY (id_pregunta) REFERENCES pregunta(id_pregunta),
    CONSTRAINT fk_respuesta_opcion
        FOREIGN KEY (id_opcion) REFERENCES opcion_respuesta(id_opcion),
    CONSTRAINT uk_respuesta_pregunta
        UNIQUE (id_evaluacion, subprueba_codigo, id_pregunta, orden_entrada),
    -- Sin pregunta solo se admiten las palabras de Fluidez Verbal (FV), hasta 75 entradas.
    CONSTRAINT ck_respuesta_fv CHECK (
        id_pregunta IS NOT NULL
        OR (UPPER(subprueba_codigo) = 'FV'
            AND orden_entrada BETWEEN 1 AND 75
            AND valor_texto IS NOT NULL
            AND LENGTH(BTRIM(valor_texto)) > 0))
);

CREATE UNIQUE INDEX uq_respuesta_fv_orden
    ON respuesta_evaluacion(id_evaluacion, subprueba_codigo, orden_entrada)
    WHERE id_pregunta IS NULL;

CREATE INDEX idx_respuesta_evaluacion
    ON respuesta_evaluacion(id_evaluacion, subprueba_codigo);

-- Entrega durable al evaluador, sin formulas de puntuacion.
CREATE TABLE solicitud_calculo_subprueba (
    id_evaluacion_subprueba BIGINT PRIMARY KEY,
    id_evaluacion BIGINT NOT NULL,
    codigo_test VARCHAR(80) NOT NULL,
    codigo_subprueba VARCHAR(80) NOT NULL,
    fecha_cierre TIMESTAMPTZ NOT NULL,
    procesada_en TIMESTAMPTZ,

    CONSTRAINT fk_solicitud_calculo_subprueba
        FOREIGN KEY (id_evaluacion_subprueba)
        REFERENCES evaluacion_subprueba(id_evaluacion_subprueba) ON DELETE CASCADE,
    CONSTRAINT fk_solicitud_calculo_evaluacion
        FOREIGN KEY (id_evaluacion) REFERENCES evaluacion(id_evaluacion) ON DELETE CASCADE
);

CREATE INDEX idx_solicitud_calculo_pendiente
    ON solicitud_calculo_subprueba(fecha_cierre, id_evaluacion_subprueba)
    WHERE procesada_en IS NULL;
