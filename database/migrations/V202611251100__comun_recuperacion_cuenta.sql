CREATE TABLE recuperacion_cuenta (
    id_recuperacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cuenta BIGINT NOT NULL REFERENCES cuenta(id_cuenta),
    resumen_token VARCHAR(64) NOT NULL UNIQUE,
    creada_en TIMESTAMPTZ NOT NULL,
    expira_en TIMESTAMPTZ NOT NULL,
    usada_en TIMESTAMPTZ,
    CONSTRAINT ck_recuperacion_vigencia CHECK (expira_en > creada_en),
    CONSTRAINT ck_recuperacion_uso CHECK (usada_en IS NULL OR usada_en >= creada_en)
);
CREATE INDEX ix_recuperacion_cuenta ON recuperacion_cuenta(id_cuenta);
